import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

// Ship the controller's authoritative migrations and workspace normalization.
// Generated JS keeps the installed plugin independent of this checkout.
for (const [source, target] of [
  ['packages/controller/src/run/db.ts', 'integrations/dsh-package/lib/relay-db.js'],
  ['packages/controller/src/workspace/key.ts', 'integrations/dsh-package/lib/workspace-key.js'],
]) {
  const input = fs.readFileSync(new URL('../' + source, import.meta.url), 'utf8');
  const output = '// Generated by scripts/build-dsh-package.mjs from ' + source + '\n'
    + stripTypeScriptTypes(input).replace(/^[^\S\r\n]+$/gm, '');
  fs.writeFileSync(new URL('../' + target, import.meta.url), output);
}
